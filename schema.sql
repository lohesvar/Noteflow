-- PostgreSQL schema for NoteFlow. Run once in Supabase SQL Editor or with psql.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hash_id TEXT NOT NULL UNIQUE,
    user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    category TEXT NOT NULL
        CHECK (category IN ('Personal', 'Work', 'Code', 'Ideas', 'Journal')),
    expiry TEXT NOT NULL DEFAULT 'never'
        CHECK (expiry IN ('never', 'burn', '1h', '24h')),
    password_hash TEXT,
    is_public BOOLEAN NOT NULL DEFAULT TRUE,
    views INTEGER NOT NULL DEFAULT 0 CHECK (views >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS notes_user_created_at_idx
    ON notes (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS notes_public_created_at_idx
    ON notes (created_at DESC)
    WHERE is_public = TRUE;
CREATE INDEX IF NOT EXISTS notes_category_idx
    ON notes (category);
